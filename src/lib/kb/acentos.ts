const SUFFIX: [RegExp, string][] = [
  [/coes$/, "ções"],
  [/cao$/, "ção"],
  [/soes$/, "sões"],
  [/([^s])sao$/, "$1são"],
  [/encia(s?)$/, "ência$1"],
  [/ancia(s?)$/, "ância$1"],
  [/iveis$/, "íveis"],
  [/aveis$/, "áveis"],
  [/ivel$/, "ível"],
  [/avel$/, "ável"],
];

function fixWord(w: string): string {
  const lower = w.toLowerCase();
  let out = WORDS[lower];
  if (!out && lower.length > 4) {
    for (const [re, rep] of SUFFIX)
      if (re.test(lower)) {
        out = lower.replace(re, rep);
        break;
      }
  }
  if (!out || out === lower) return w;
  if (w === w.toUpperCase() && w.length > 1) return out.toUpperCase();
  if (w[0] === w[0]!.toUpperCase()) return out[0]!.toUpperCase() + out.slice(1);
  return out;
}

export function fixAccents(text: string): string {
  return text.replace(/\b[A-Za-z]+\b/g, fixWord);
}
